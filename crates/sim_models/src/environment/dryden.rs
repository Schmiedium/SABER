//! Dryden turbulence (MIL-HDBK-1797, MIL-F-8785C; build step 5c).
//!
//! Three independent gust components `u` (longitudinal), `v` (lateral) and `w` (vertical) with the
//! Dryden spectra over spatial frequency `Ω` (rad/m), one-sided so that `∫₀^∞ Φ dΩ = σ²`:
//!
//! ```text
//! Φ_u(Ω) = σ_u² (2 L_u / π) · 1 / (1 + (L_u Ω)²)
//! Φ_v(Ω) = σ_v² (L_v / π) · (1 + 3 (L_v Ω)²) / (1 + (L_v Ω)²)²      (and w with σ_w, L_w)
//! ```
//!
//! These are MIL-F-8785C's forms. MIL-HDBK-1797 writes the lateral and vertical spectra with half
//! the scale length (`2L` for `L`, `12 L²Ω²` and `4 L²Ω²`), which is the same spectrum once its
//! lengths are doubled: give `L_v` and `L_w` here in the MIL-F-8785C sense. The field is frozen
//! (Taylor's hypothesis): a body flying at `V` through it sees the spatial pattern at `ξ = V t`, so
//! the autocorrelations in time are
//!
//! ```text
//! R_u(τ) = σ_u² e^{−Vτ/L_u}            R_v(τ) = σ_v² (1 − Vτ / 2L_v) e^{−Vτ/L_v}
//! ```
//!
//! Each component is generated by the exact discretisation of its shaping filter driven by
//! continuous white noise, so the samples on the tick grid have exactly these autocorrelations at
//! any tick length, with no dependence on how short the tick is. `u` is a first-order
//! Gauss–Markov process. `v` and `w` each have two states, scaled so the stationary state is two
//! independent unit normals `z₁, z₂` and the gust is `σ (z₁ + √3 z₂) / 2`; with `θ = V dt / L` the
//! transition is `e^{−θ} [[1 + θ, θ], [−θ, 1 − θ]]` and the process noise covariance is
//! `4 [[J₂, J₁ − J₂], [J₁ − J₂, J₀ − 2J₁ + J₂]]` with `J_k = ∫₀^θ s^k e^{−2s} ds`. The generator
//! starts from the stationary distribution, so a run's statistics do not depend on how long it has
//! been going.
//!
//! Every step draws five standard normals, `u`, `v₁`, `v₂`, `w₁`, `w₂` in that order, whatever the
//! intensities, so changing one intensity never shifts another component's draws.

use sim_core::RngStream;

/// The Dryden spectrum parameters.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct DrydenSpec {
    /// Speed `V` at which the field is traversed, m/s.
    pub airspeed: f64,
    /// RMS intensities `(σ_u, σ_v, σ_w)`, m/s.
    pub intensity: [f64; 3],
    /// Scale lengths `(L_u, L_v, L_w)`, m, in MIL-F-8785C's sense (see the module notes). A length
    /// whose intensity is zero is not used.
    pub scale: [f64; 3],
}

impl DrydenSpec {
    /// Check the parameters.
    pub fn validate(&self) -> Result<(), String> {
        if !(self.airspeed.is_finite() && self.airspeed > 0.0) {
            return Err(format!(
                "Dryden airspeed {} must be finite and > 0",
                self.airspeed
            ));
        }
        for (k, name) in ["u", "v", "w"].iter().enumerate() {
            let (s, l) = (self.intensity[k], self.scale[k]);
            if !(s.is_finite() && s >= 0.0) {
                return Err(format!("Dryden σ_{name} = {s} must be finite and ≥ 0"));
            }
            if s > 0.0 && !(l.is_finite() && l > 0.0) {
                return Err(format!("Dryden L_{name} = {l} must be finite and > 0"));
            }
        }
        Ok(())
    }
}

/// The exact one-tick transition of the two-state lateral/vertical shaping filter, in the
/// coordinates where its stationary state is two independent unit normals.
#[derive(Clone, Copy, Debug, PartialEq)]
struct SecondOrder {
    phi: [[f64; 2]; 2],
    /// Lower Cholesky factor of the process noise covariance: `[l11, l21, l22]`.
    chol: [f64; 3],
}

impl SecondOrder {
    fn new(theta: f64) -> Self {
        let e = (-theta).exp();
        let (j0, j1, j2) = (j(0, theta), j(1, theta), j(2, theta));
        let q11 = 4.0 * j2;
        let q12 = 4.0 * (j1 - j2);
        let q22 = 4.0 * (j0 - 2.0 * j1 + j2);
        let l11 = q11.sqrt();
        let l21 = if l11 > 0.0 { q12 / l11 } else { 0.0 };
        let l22 = (q22 - l21 * l21).max(0.0).sqrt();
        Self {
            phi: [
                [e * (1.0 + theta), e * theta],
                [-e * theta, e * (1.0 - theta)],
            ],
            chol: [l11, l21, l22],
        }
    }

    fn step(&self, z: [f64; 2], n: [f64; 2]) -> [f64; 2] {
        let [l11, l21, l22] = self.chol;
        [
            self.phi[0][0] * z[0] + self.phi[0][1] * z[1] + l11 * n[0],
            self.phi[1][0] * z[0] + self.phi[1][1] * z[1] + l21 * n[0] + l22 * n[1],
        ]
    }
}

/// `J_k(θ) = ∫₀^θ s^k e^{−2s} ds` for `k ≤ 2`, accurate for small `θ` (a power series below
/// `θ = ½`, where the closed forms cancel) and large.
fn j(k: u32, theta: f64) -> f64 {
    if theta <= 0.5 {
        // θ^{k+1} Σ_m (−2θ)^m / (m! (k + m + 1)); the terms fall by at least m+1 each.
        let x = -2.0 * theta;
        let mut term = 1.0;
        let mut sum = 0.0;
        for m in 0..40 {
            sum += term / f64::from(k + m + 1);
            term *= x / f64::from(m + 1);
        }
        theta.powi(k as i32 + 1) * sum
    } else {
        let e = (-2.0 * theta).exp();
        match k {
            0 => (1.0 - e) / 2.0,
            1 => (1.0 - e * (1.0 + 2.0 * theta)) / 4.0,
            _ => (2.0 - e * (2.0 + 4.0 * theta + 4.0 * theta * theta)) / 8.0,
        }
    }
}

/// A Dryden gust generator on a fixed tick.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct DrydenTurbulence {
    sigma: [f64; 3],
    u_decay: f64,
    u_drive: f64,
    lateral: [SecondOrder; 2],
    /// `z_u`, then `z₁, z₂` for `v` and for `w`: unit-variance when stationary.
    z: [f64; 5],
}

impl DrydenTurbulence {
    /// The generator for `spec` on a tick of `dt` seconds, at rest until [`start`](Self::start).
    pub fn new(spec: &DrydenSpec, dt: f64) -> Result<Self, String> {
        spec.validate()?;
        if !(dt.is_finite() && dt > 0.0) {
            return Err(format!("Dryden tick {dt} must be finite and > 0"));
        }
        // A component with zero intensity keeps a harmless placeholder length.
        let theta = |k: usize| {
            if spec.intensity[k] > 0.0 {
                spec.airspeed * dt / spec.scale[k]
            } else {
                1.0
            }
        };
        let tu = theta(0);
        Ok(Self {
            sigma: spec.intensity,
            u_decay: (-tu).exp(),
            u_drive: (-(-2.0 * tu).exp_m1()).sqrt(),
            lateral: [SecondOrder::new(theta(1)), SecondOrder::new(theta(2))],
            z: [0.0; 5],
        })
    }

    /// Draw the state from the stationary distribution (five normals).
    pub fn start(&mut self, rng: &mut RngStream) {
        for z in &mut self.z {
            *z = rng.standard_normal();
        }
    }

    /// Advance one tick (five normals).
    pub fn step(&mut self, rng: &mut RngStream) {
        let n: [f64; 5] = std::array::from_fn(|_| rng.standard_normal());
        self.z[0] = self.u_decay * self.z[0] + self.u_drive * n[0];
        let v = self.lateral[0].step([self.z[1], self.z[2]], [n[1], n[2]]);
        let w = self.lateral[1].step([self.z[3], self.z[4]], [n[3], n[4]]);
        self.z[1..].copy_from_slice(&[v[0], v[1], w[0], w[1]]);
    }

    /// The gust `(u, v, w)`, m/s.
    pub fn gust(&self) -> [f64; 3] {
        let half_root3 = 0.5 * 3f64.sqrt();
        [
            self.sigma[0] * self.z[0],
            self.sigma[1] * (0.5 * self.z[1] + half_root3 * self.z[2]),
            self.sigma[2] * (0.5 * self.z[3] + half_root3 * self.z[4]),
        ]
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_series_and_the_closed_forms_agree_at_the_switch() {
        let theta: f64 = 0.5;
        let e = (-2.0 * theta).exp();
        let closed = [
            (1.0 - e) / 2.0,
            (1.0 - e * (1.0 + 2.0 * theta)) / 4.0,
            (2.0 - e * (2.0 + 4.0 * theta + 4.0 * theta * theta)) / 8.0,
        ];
        for k in 0..3 {
            let rel = (j(k, theta) - closed[k as usize]).abs() / closed[k as usize];
            assert!(rel < 1e-14, "J_{k}: {rel:e}");
        }
    }

    /// Two half-ticks make one tick, in mean and covariance: `Φ(θ) = Φ(θ/2)²` and
    /// `Q(θ) = Φ(θ/2) Q(θ/2) Φ(θ/2)ᵀ + Q(θ/2)`, at tiny steps (the series branch, where the
    /// closed forms would cancel) and across the switch between the branches.
    #[test]
    fn two_half_steps_make_one_step() {
        let q = |s: &SecondOrder| {
            let [l11, l21, l22] = s.chol;
            [[l11 * l11, l11 * l21], [l11 * l21, l21 * l21 + l22 * l22]]
        };
        let mul = |a: [[f64; 2]; 2], b: [[f64; 2]; 2]| -> [[f64; 2]; 2] {
            std::array::from_fn(|r| std::array::from_fn(|c| a[r][0] * b[0][c] + a[r][1] * b[1][c]))
        };
        let tr = |a: [[f64; 2]; 2]| [[a[0][0], a[1][0]], [a[0][1], a[1][1]]];
        for theta in [1e-7, 1e-3, 0.3, 0.9, 3.0] {
            let (whole, half) = (SecondOrder::new(theta), SecondOrder::new(0.5 * theta));
            let phi2 = mul(half.phi, half.phi);
            let qh = q(&half);
            let q2 = mul(mul(half.phi, qh), tr(half.phi));
            let qw = q(&whole);
            for r in 0..2 {
                for c in 0..2 {
                    assert!((phi2[r][c] - whole.phi[r][c]).abs() < 1e-15, "Φ θ {theta}");
                    let want = q2[r][c] + qh[r][c];
                    assert!(
                        (want - qw[r][c]).abs() <= 1e-12 * qw[r][c].abs().max(1e-300),
                        "Q θ {theta} [{r}][{c}]: {want:e} vs {:e}",
                        qw[r][c]
                    );
                }
            }
        }
    }

    #[test]
    fn the_noise_covariance_is_the_stationary_deficit() {
        // P = Φ P Φᵀ + Q with P = I, checked where both forms are accurate.
        for theta in [0.3, 0.7, 2.0] {
            let s = SecondOrder::new(theta);
            let [l11, l21, l22] = s.chol;
            let q = [[l11 * l11, l11 * l21], [l11 * l21, l21 * l21 + l22 * l22]];
            for (r, c) in [(0, 0), (0, 1), (1, 0), (1, 1)] {
                let ppt: f64 = (0..2).map(|k| s.phi[r][k] * s.phi[c][k]).sum();
                let want = if r == c { 1.0 } else { 0.0 };
                assert!((ppt + q[r][c] - want).abs() < 1e-14, "θ {theta} [{r}][{c}]");
            }
        }
    }
}
